-- 5. DATABASE MANAGEMENT OPERATIONS
-- ----------------------------------------------------------------------------

-- Update employee salary
UPDATE employees SET salary = 70000.00 WHERE email = 'siva.kumar@example.com';

-- Update employee department
UPDATE employees SET department = 'Operations' WHERE email = 'rahul.mehta@example.com';

-- Find employees with salary greater than a specified amount
SELECT * FROM employees WHERE salary > 60000 AND is_active = TRUE;

-- Find the highest-paid employee
SELECT * FROM employees
WHERE is_active = TRUE
ORDER BY salary DESC
LIMIT 1;

-- Find the average salary
SELECT AVG(salary) AS average_salary FROM employees WHERE is_active = TRUE;

-- Count employees by department
SELECT department, COUNT(*) AS employee_count
FROM employees
WHERE is_active = TRUE
GROUP BY department
ORDER BY employee_count DESC;

-- Retrieve employees using SQL JOIN (employee + the user who created them)
SELECT
    e.id,
    e.name,
    e.department,
    e.salary,
    u.username AS created_by_username,
    u.role AS created_by_role
FROM employees e
JOIN users u ON e.created_by = u.id
ORDER BY e.id;

-- Identify duplicate employee emails (should return none, since email is UNIQUE;
-- this query is useful before the constraint is added, or on imported data)
SELECT email, COUNT(*) AS occurrences
FROM employees
GROUP BY email
HAVING COUNT(*) > 1;

-- Deactivate a record (soft delete, mirrors what the API's DELETE endpoint does)
UPDATE employees SET is_active = FALSE WHERE email = 'karthik.iyer@example.com';

